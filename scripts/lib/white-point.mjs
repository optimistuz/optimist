/**
 * white-point.mjs — закон белой точки. Одна реализация на весь конвейер.
 *
 * Зачем (CLAUDE.md, «Парящие оправы», рубеж 2): mix-blend-mode: multiply
 * смешивает кадр со страницей. Фон кадра обязан быть честным (255,255,255),
 * иначе вокруг оправы виден серый прямоугольник-призрак. Это не лечится
 * в вёрстке.
 *
 * ── ТРИ ПОДХОДА, ДВА ИЗ КОТОРЫХ ОКАЗАЛИСЬ НЕВЕРНЫМИ ────────────────────────
 *
 * 1. «Сэмплировать рамку кадра» (как normalize-white.ps1). Убито аудитом:
 *    на макро оправа доходит до края, «фон» уезжал на оправу, и безупречный
 *    кадр получал gain 6,4 с приговором «пересъёмка». А кадр с честной рамкой
 *    и завалом свипа в ГЛУБИНЕ проходил — и давал дымку на 70 % площади.
 *    Мерили край, а смешивается весь фон.
 *
 * 2. «Отделять фон от оправы по ЯРКОСТИ» (заливка по светлым пикселям). Тоже
 *    убито аудитом, и дважды:
 *    — светлая оправа (золото, серебро, бежевый ацетат) ярче порога заливки:
 *      «фоном» становилась сама оправа, gain улетал, годный кадр браковался.
 *      Две единицы цвета оправы решали судьбу кадра;
 *    — виньетка проходила насквозь: уровень фона брался перцентилем, тёмные
 *      углы в него не попадали, и призрак оставался на странице.
 *
 * 3. ЧТО ЗДЕСЬ: и ОПРАВА, и ТЕНЬ отделяются от фона ПО ГЕОМЕТРИИ.
 *
 *    Оправа — КРОМКОЙ. Заливка идёт от границ кадра и не проходит через резкий
 *    перепад яркости. Тёмная оправа или золотая — безразлично: кромка есть
 *    у обеих. Так снимается баг №2.
 *
 *    Тень — ТЕМ, ЧТО ОНА НЕ ДОСТАЁТ ДО КРАЁВ КАДРА. Отступать от оправы
 *    (фиксированно или по «плато» яркости) я пробовал — оба способа врали
 *    на РЕАЛЬНОМ кадре: у deco-2 отбрасываемая тень уходит далеко влево-вниз,
 *    её не покрывает никакой разумный отступ, и живой кадр, который прямо
 *    сейчас проходит пиксельный аудит ±1 на сайте, получал ложный брак.
 *    А вот виньетка, завал свипа и градиент до краёв доходят ВСЕГДА — такова
 *    их природа. Отсюда два замера:
 *      • уровень свипа У КРАЁВ — по краевым клеткам (это и мерил PS1);
 *      • уровень свипа В ЦЕЛОМ — по преобладающей массе фона (тень в ней
 *        меньшинство, ровная пелена — большинство).
 *    Усиление берём по меньшему из двух. Тень остаётся тенью, пелена лечится.
 *
 * ── ЧТО ЛЕЧИТСЯ УСИЛЕНИЕМ, А ЧТО НЕТ ──────────────────────────────────────
 *
 * РОВНАЯ пелена лечится: нормализуем по уровню фона, он становится 255, всё
 * светлее — клиппится в 255. Замер: свип 236 → gain 1,0805 → призрак 0.
 *
 * ВИНЬЕТКА не лечится ПРИНЦИПИАЛЬНО: скалярное усиление не выпрямляет градиент.
 * Дотянешь угол — пересветишь центр; нормализуешь по центру — угол останется
 * серым. Поэтому неравномерный фон — БРАК, а не «подтянем сильнее». Бриф §1.1
 * запрещает виньетку прямо, и гейт равномерности (SPREAD_MAX) её ловит.
 *
 * ⚠️ `normalize-white.ps1` остаётся инструментом СЪЁМОЧНОГО ДНЯ и меряет
 * по-прежнему рамку: это быстрый скрининг за минуту без node. Обязывающий
 * гейт — здесь. Предохранитель НЕ дублируется: он читается из PS1.
 *
 * Калибровано по РЕАЛЬНЫМ кадрам (deco-1/2/3, hero-float — живут на сайте
 * и проходят аудит ±1): все четыре дают gain 1,0000 и разброс 0.
 */
import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

/** Ширина, до которой уменьшаем кадр для анализа: быстро и гасит шум JPEG. */
const ANALYSIS_WIDTH = 800;

/**
 * Перепад яркости, который считается КРОМКОЙ объекта. Заливка через него
 * не проходит. Шум ровного свипа — 1–3 единицы; виньетка меняется на единицы
 * на сотни пикселей. Кромка оправы — десятки единиц на один пиксель.
 */
const EDGE_STEP = 10;

/** Ниже этого стартовать заливку нельзя: пиксель границы кадра занят объектом. */
const SEED_MIN = 150;

/**
 * Допустимый разброс фона по краю кадра (p90 − p10 по краевым клеткам).
 *
 * Это гейт виньетки. Замер по синтетическим кадрам: углы 252 → разброс 2,
 * призрак 1 (в допуске ±1); углы 246 → разброс 5, призрак 2 (уже вне допуска);
 * углы 240 → разброс 9. Реальные кадры сайта дают разброс 0. Порог 4 пропускает
 * только тот фон, который усиление действительно дожимает до белого.
 */
const SPREAD_MAX = 4;

/** Доля кадра, ниже которой фон считается не найденным. */
const MIN_BG_FRACTION = 0.06;

/**
 * Пороги «заливка не дошла до фона» (см. backgroundStats).
 *
 * Решающий признак — НЕ яркость запертой массы, а ТЕМНОТА БАРЬЕРА, который
 * заливку остановил. Разница физическая:
 *   • на честном кадре заливку останавливает МАТЕРИАЛ ОПРАВЫ — барьер тёмный;
 *   • на кадре с каймой (перелив свипа, вклейка в белый холст) заливку
 *     останавливает СТУПЕНЬКА ЭКСПОЗИЦИИ на светлое плато — барьер светлый.
 *
 * Яркости самой запертой массы верить нельзя: «объект» — это всё, куда заливка
 * не дошла, и туда попадают ИНТЕРЬЕРЫ ЛИНЗ (прозрачное стекло над белым свипом,
 * 250–255). Замер по живым blend-кадрам сайта: deco-1 и deco-3 дают медиану
 * «объекта» 254 при gain 1,0000 — то есть «светлая масса» есть у безупречных
 * кадров, и одна она означала бы ложный брак на первом же макро.
 *
 * Замер барьера: кайма-ловушка — 218; честное макро deco-1 (носоупоры) — 19;
 * макро с оправой у края — 18; deco-2 — 69. Порог 180 разделяет их с запасом.
 */
const VEIL_AREA = 0.5;
const VEIL_LUM = 200;
const VEIL_BARRIER_LUM = 180;
/** Полоса, на которой меряется барьер: 3–8 px вглубь объекта от границы фона. */
const BARRIER_NEAR = 3;
const BARRIER_FAR = 8;

/**
 * Доля, ВЫШЕ которой «фон» подозрителен: в кадре есть оправа, значит фоном
 * не может быть весь кадр. Если заливка растеклась на объект — мы обязаны
 * отказаться судить, а не выносить уверенный приговор.
 */
const MAX_BG_FRACTION = 0.93;

/**
 * Предохранитель выжигания — из `normalize-white.ps1`, единственного места,
 * где это число живёт. Поменяют там и забудут здесь — конвейер остановится,
 * а не опубликует серый прямоугольник.
 */
export async function readMaxGain(root) {
  const ps1 = path.join(root, "scripts", "normalize-white.ps1");
  const src = await fs.readFile(ps1, "utf8");
  const m = src.match(/\[double\]\$MaxGain\s*=\s*([\d.]+)/);
  if (!m) {
    throw new Error(
      "не нашёл $MaxGain в scripts/normalize-white.ps1 — предохранитель белой точки потерян. " +
        "Число должно быть одно на два скрипта; собирать «на глаз» конвейер не станет."
    );
  }
  return Number(m[1]);
}

function percentile(values, p) {
  const sorted = values.sort((a, b) => a - b);
  return sorted[Math.min(sorted.length - 1, Math.floor(sorted.length * p))];
}

/**
 * Яркость БАРЬЕРА — стенки, о которую разбилась заливка.
 *
 * Меряется полоса 3–8 px вглубь «объекта» от границы фона. Первые 2 px
 * пропускаем: там кромка размазана оптикой и сжатием, и её полутон одинаков
 * и у обода, и у ступеньки — по нему их не различить.
 *
 * Тёмный барьер = обод оправы (кадр честный, объект — просто крупный).
 * Светлый барьер = ступенька экспозиции (заливка встала на кайме, а фон
 * остался за ней НЕ измеренным).
 */
function barrierLum(mask, lum, w, h, n) {
  const dist = new Int16Array(n); // 0 — не размечено
  const queue = new Int32Array(n);
  let head = 0;
  let tail = 0;

  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const p = y * w + x;
      if (mask[p]) continue;
      const touchesBg =
        (x > 0 && mask[p - 1]) ||
        (x < w - 1 && mask[p + 1]) ||
        (y > 0 && mask[p - w]) ||
        (y < h - 1 && mask[p + w]);
      if (touchesBg) {
        dist[p] = 1;
        queue[tail++] = p;
      }
    }
  }

  while (head < tail) {
    const p = queue[head++];
    if (dist[p] >= BARRIER_FAR) continue;
    const x = p % w;
    const y = (p / w) | 0;
    const step = (q) => {
      if (!mask[q] && dist[q] === 0) {
        dist[q] = dist[p] + 1;
        queue[tail++] = q;
      }
    };
    if (x > 0) step(p - 1);
    if (x < w - 1) step(p + 1);
    if (y > 0) step(p - w);
    if (y < h - 1) step(p + w);
  }

  const band = [];
  for (let p = 0; p < n; p++) {
    if (dist[p] >= BARRIER_NEAR && dist[p] <= BARRIER_FAR) band.push(lum[p]);
  }
  return band.length ? percentile(band, 0.5) : 255;
}


/**
 * Маска фона и его статистика.
 *
 * Возвращает { fraction, min:{r,g,b}, spread, insufficient?, overgrown? }.
 * `spread` — разброс фона (p99 − p0.5): мера виньетки/градиента.
 */
export async function backgroundStats(input, { crop } = {}) {
  let pipe = sharp(input).removeAlpha();
  if (crop) {
    const meta = await sharp(input).metadata();
    pipe = sharp(input)
      .removeAlpha()
      .extract({
        left: Math.round(crop[0] * meta.width),
        top: Math.round(crop[1] * meta.height),
        width: Math.round(crop[2] * meta.width),
        height: Math.round(crop[3] * meta.height),
      });
  }
  const { data, info } = await pipe
    .resize({ width: ANALYSIS_WIDTH, withoutEnlargement: true })
    .raw()
    .toBuffer({ resolveWithObject: true });

  const { width: w, height: h, channels: ch } = info;
  const n = w * h;

  const lum = new Uint8Array(n); // минимум по каналам: «насколько пиксель тёмный»
  for (let p = 0, i = 0; p < n; p++, i += ch) {
    lum[p] = Math.min(data[i], data[i + 1], data[i + 2]);
  }

  // Кромки: где яркость прыгает. Через кромку заливка не идёт — так объект
  // отделяется от фона независимо от того, светлый он или тёмный.
  const edge = new Uint8Array(n);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const p = y * w + x;
      const v = lum[p];
      let step = 0;
      if (x > 0) step = Math.max(step, Math.abs(v - lum[p - 1]));
      if (x < w - 1) step = Math.max(step, Math.abs(v - lum[p + 1]));
      if (y > 0) step = Math.max(step, Math.abs(v - lum[p - w]));
      if (y < h - 1) step = Math.max(step, Math.abs(v - lum[p + w]));
      edge[p] = step >= EDGE_STEP ? 1 : 0;
    }
  }

  // Заливка от границ кадра: по не-кромочным пикселям. Плавный градиент
  // (виньетка, завал свипа) заливка проходит — он и есть фон.
  const mask = new Uint8Array(n);
  const queue = new Int32Array(n);
  let head = 0;
  let tail = 0;
  const push = (p) => {
    if (!mask[p] && !edge[p] && lum[p] >= SEED_MIN) {
      mask[p] = 1;
      queue[tail++] = p;
    }
  };
  for (let x = 0; x < w; x++) {
    push(x);
    push((h - 1) * w + x);
  }
  for (let y = 0; y < h; y++) {
    push(y * w);
    push(y * w + w - 1);
  }
  while (head < tail) {
    const p = queue[head++];
    const x = p % w;
    const y = (p / w) | 0;
    if (x > 0) push(p - 1);
    if (x < w - 1) push(p + 1);
    if (y > 0) push(p - w);
    if (y < h - 1) push(p + w);
  }

  // ТЕНЬ ОТДЕЛЯЕТСЯ ОТ ФОНА НЕ РАССТОЯНИЕМ, А ТЕМ, ЧТО ОНА НЕ ДОСТАЁТ ДО КРАЁВ.
  //
  // Пробовал отступать от оправы (фиксированно и по «плато» яркости) — оба
  // способа врали на РЕАЛЬНОМ кадре: у deco-2 отбрасываемая тень уходит далеко
  // влево-вниз, любой разумный отступ её не покрывает, и живой кадр, который
  // прямо сейчас проходит пиксельный аудит ±1 на сайте, получал ложный брак.
  //
  // Настоящее различие — геометрическое, и оно простое: контактная тень
  // ПРИВЯЗАНА К ОПРАВЕ и до границ кадра не доходит. Виньетка, завал свипа
  // и градиент — доходят, это их природа. Поэтому:
  //   • уровень свипа у КРАЁВ кадра — по краевым клеткам (это и мерил PS1);
  //   • уровень свипа В ЦЕЛОМ — по преобладающей массе фона (тень в ней
  //     меньшинство, а сплошная пелена — большинство).
  // Усиление берём по меньшему из двух. Тень остаётся тенью, пелена лечится,
  // виньетка ловится гейтом равномерности.

  // Фон меряется КЛЕТКАМИ, а не общей кучей пикселей.
  //
  // Почему: нам нужна самая тёмная область ФОНА (угол виньетки), но не редкий
  // тёмный пиксель (хвост тени, пылинка, звон JPEG). Перцентиль по всей куче
  // их не различает: и то и другое — «тёмный хвост». А клетка различает —
  // тёмный угол виньетки заполняет свою клетку целиком и роняет её медиану,
  // а хвост тени внутри клетки тонет в её же медиане.
  const CELL = Math.max(16, Math.round(w / 24));
  const cols = Math.ceil(w / CELL);
  const rows = Math.ceil(h / CELL);
  const cells = Array.from({ length: cols * rows }, () => ({ r: [], g: [], b: [], l: [] }));

  let bgPixels = 0;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const p = y * w + x;
      if (!mask[p]) continue;
      const c = cells[Math.floor(y / CELL) * cols + Math.floor(x / CELL)];
      const i = p * ch;
      c.r.push(data[i]);
      c.g.push(data[i + 1]);
      c.b.push(data[i + 2]);
      c.l.push(lum[p]);
      bgPixels++;
    }
  }

  const fraction = bgPixels / n;
  // Фоном оказался почти весь кадр — заливка перелезла на объект (кромка
  // не читается: светлая оправа в тон собственной тени, мягкий фокус, обтравка).
  // Уверенный приговор здесь был бы враньём.
  //
  // НО: если оператор задал --crop, он САМ показал, где фон, — и «фон занимает
  // весь кусок» перестаёт быть подозрением, становясь ожиданием. Иначе
  // аварийный выход не спасал бы: он вёл бы в тот же тупик.
  if (!crop && fraction > MAX_BG_FRACTION) {
    return { fraction, overgrown: true };
  }

  // ЗЕРКАЛЬНЫЙ ОТКАЗ: заливка НЕ ДОШЛА до фона.
  //
  // Заливка встаёт на любой ступеньке яркости, а ступенька бывает не только
  // у кромки оправы: светлая кайма по периметру (перелив свипа к краям, ретушь,
  // кадр, вклеенный в белый холст) — тоже ступенька. Тогда «фоном» объявляется
  // сама кайма, её уровень 255, и заваленный свип в глубине кадра получает
  // gain 1,0 «годен». Именно так брак и уходил бы на сайт: закон обещает мерить
  // ВЕСЬ фон, а мерил бы рамку — ровно ту болезнь, ради которой его переписали.
  //
  // Порогом яркости ступеньки эти два случая не развести: у СВЕТЛОЙ оправы
  // ступенька (255→232) МЕЛЬЧЕ, чем у заваленного свипа (255→218), — то есть
  // «пускать заливку через мелкие ступеньки» сломало бы светлые оправы.
  //
  // Различие — в БАРЬЕРЕ, а не в том, что за ним заперто. Заливку остановил
  // материал оправы (тёмный обод) — кадр честный, объект просто крупный.
  // Заливку остановила ступенька экспозиции (светлое плато) — фон не измерен.
  //
  // Яркость самой запертой массы решающей быть НЕ МОЖЕТ: в «объект» попадают
  // интерьеры линз (прозрачное стекло над свипом, 250–255), и живые deco-1/
  // deco-3, безупречные по белой точке, дают медиану объекта 254. Порог по ней
  // одной забраковал бы честное макро с прозрачными линзами — ложный брак
  // страшнее исходной дыры: он убивает годный артикул в день съёмки.
  if (!crop && 1 - fraction > VEIL_AREA) {
    const objLum = [];
    for (let p = 0; p < n; p++) if (!mask[p]) objLum.push(lum[p]);
    if (
      percentile(objLum, 0.5) >= VEIL_LUM &&
      barrierLum(mask, lum, w, h, n) >= VEIL_BARRIER_LUM
    ) {
      return { fraction, insufficient: true, veiled: true };
    }
  }

  // Клетка засчитывается, только если она ПОЧТИ ЦЕЛИКОМ фон: иначе её медиану
  // тянет вниз оправа, задевшая угол клетки.
  const MIN_CELL_FILL = 0.7;
  const idx = [];
  const good = [];
  cells.forEach((c, k) => {
    if (c.l.length >= CELL * CELL * MIN_CELL_FILL) {
      good.push(c);
      idx.push(k);
    }
  });
  if (fraction < MIN_BG_FRACTION || good.length < 8) {
    return { fraction, insufficient: true };
  }

  const med = (c, k) => percentile(c[k], 0.5);

  // Краевые клетки: сюда тень не достаёт, а виньетка и завал свипа — достают.
  const isBorder = (k) => {
    const cx = k % cols;
    const cy = Math.floor(k / cols);
    return cx === 0 || cy === 0 || cx === cols - 1 || cy === rows - 1;
  };
  const border = good.filter((_, i) => isBorder(idx[i]));
  if (border.length < 4) return { fraction, insufficient: true };

  // По краю берём 10-й перцентиль, а не минимум: одна клетка, задетая длинной
  // тенью, не должна решать судьбу кадра, — а виньетка темнит СРАЗУ МНОГО
  // краевых клеток и из перцентиля не спрячется.
  const level = (list, k, p) => percentile(list.map((c) => med(c, k)), p);
  const borderLevel = {
    r: level(border, "r", 0.1),
    g: level(border, "g", 0.1),
    b: level(border, "b", 0.1),
  };

  // Преобладающий уровень фона: тень — меньшинство, сплошная пелена —
  // большинство. Поэтому 75-й перцентиль по всем клеткам видит свип и
  // не видит тени, но пелену увидит: при пелене ВСЕ клетки темнее.
  const sweepLevel = {
    r: level(good, "r", 0.75),
    g: level(good, "g", 0.75),
    b: level(good, "b", 0.75),
  };

  const borderLums = border.map((c) => med(c, "l"));

  return {
    fraction,
    cells: good.length,
    borderCells: border.length,
    // Нормализуем по МЕНЬШЕМУ из двух: и край, и масса фона обязаны стать белыми.
    min: {
      r: Math.min(borderLevel.r, sweepLevel.r),
      g: Math.min(borderLevel.g, sweepLevel.g),
      b: Math.min(borderLevel.b, sweepLevel.b),
    },
    // Разброс по КРАЮ кадра: ровный свип даёт единицы, виньетка — десятки.
    spread: percentile([...borderLums], 0.9) - percentile([...borderLums], 0.1),
    pixels: bgPixels,
  };
}

/** gain = 255/min по каналам: сколько нужно, чтобы САМАЯ ТЁМНАЯ точка фона стала белой. */
export function gainsOf(stats) {
  return { r: 255 / stats.min.r, g: 255 / stats.min.g, b: 255 / stats.min.b };
}

/**
 * Приговор кадру «на белом». Возвращает { ok, gain, worst, spread, reason }.
 * «Фон не измерен» — НЕ брак кадра: это отказ мерить, и лечится он --crop.
 */
export async function judge(input, { maxGain, crop } = {}) {
  const stats = await backgroundStats(input, { crop });

  if (stats.veiled) {
    return {
      ok: false,
      unmeasurable: true,
      fraction: stats.fraction,
      reason:
        `замер не дошёл до фона: фоном читается только ${(stats.fraction * 100).toFixed(0)} % кадра ` +
        `(светлая кайма по краю), а вся глубина кадра — светлая и НЕ измерена. ` +
        `Так выглядит перелив свипа к краям или кадр, вклеенный в белый холст. ` +
        `Сказать «годен» здесь — соврать: под каймой может лежать серый фон. ` +
        `Покажите, где фон, — --crop x,y,w,h (доли 0..1), как -CropRect у normalize-white.ps1.`,
    };
  }
  if (stats.insufficient) {
    return {
      ok: false,
      unmeasurable: true,
      fraction: stats.fraction,
      reason:
        `фон не читается (найдено ${(stats.fraction * 100).toFixed(1)} % кадра). ` +
        `Объект занимает почти весь кадр, либо фон не белый. Это НЕ приговор кадру: ` +
        `покажите, где фон, — --crop x,y,w,h (доли 0..1), как -CropRect у normalize-white.ps1.`,
    };
  }
  if (stats.overgrown) {
    return {
      ok: false,
      unmeasurable: true,
      fraction: stats.fraction,
      reason:
        `фоном оказался почти весь кадр (${(stats.fraction * 100).toFixed(0)} %) — кромка объекта ` +
        `не читается, замер перелез на оправу. Уверенный приговор здесь был бы враньём. ` +
        `Задайте зону фона через --crop x,y,w,h.`,
    };
  }

  const gain = gainsOf(stats);
  const worst = Math.max(gain.r, gain.g, gain.b);
  const darkest = Math.min(stats.min.r, stats.min.g, stats.min.b);

  // Неравномерный фон — брак ДО всякого усиления: скалярным gain градиент
  // не выпрямляется, и призрак останется, как бы мы ни тянули.
  if (stats.spread > SPREAD_MAX) {
    return {
      ok: false,
      gain,
      worst,
      spread: stats.spread,
      fraction: stats.fraction,
      reason:
        `фон неравномерен: разброс ${stats.spread} при допуске ${SPREAD_MAX} — виньетка, ` +
        `завал свипа или градиент. Бриф §1.1 это запрещает: усиление такой фон НЕ выпрямляет ` +
        `(угол останется серым и будет виден на странице). Ровный свет по фону — и ПЕРЕСЪЁМКА.`,
    };
  }

  if (worst > maxGain) {
    return {
      ok: false,
      gain,
      worst,
      spread: stats.spread,
      fraction: stats.fraction,
      reason:
        `gain ${worst.toFixed(4)} > предохранителя ${maxGain}: самая тёмная точка фона — ${darkest} ` +
        `(нужно ≥ ${Math.ceil(255 / maxGain)}). ` +
        (stats.spread > 12
          ? `Фон неравномерен (разброс ${stats.spread}) — похоже на виньетку или завал свипа. `
          : `Фон тёмный целиком. `) +
        `Нормализация выжгла бы тень под оправой. ПЕРЕСЪЁМКА.`,
    };
  }

  return { ok: true, gain, worst, spread: stats.spread, fraction: stats.fraction };
}

/**
 * Проверка уже записанного файла: весь фон обязан стать 255.
 * Никакой амнистии: усиление считалось ПО МИНИМУМУ фона, значит после него
 * минимум фона равен 255 по построению. Если нет — что-то не сошлось.
 */
export async function verifyPublished(file) {
  const stats = await backgroundStats(file);
  // «Замер не дошёл до фона» — НЕ повод амнистировать опубликованный кадр:
  // под каймой может лежать серый свип, и молчание здесь выключало бы проверку
  // ровно там, где прибор меньше всего уверен. Кадр, который нечем проверить,
  // публикации не подлежит.
  if (stats.veiled) {
    return { ok: false, veiled: true, fraction: stats.fraction };
  }
  if (stats.insufficient || stats.overgrown) return { ok: true, skipped: true };
  const min = Math.min(stats.min.r, stats.min.g, stats.min.b);
  return { ok: min >= 254, min, spread: stats.spread };
}

