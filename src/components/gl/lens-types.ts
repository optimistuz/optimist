/**
 * Общие типы линзы. ОТДЕЛЬНЫМ модулем — чтобы триггер в критическом пути «/»
 * (`ui/lens-loupe.tsx`) не импортировал ничего из ленивой части: тип стирается
 * при сборке, а импорт значения утащил бы за собой и реализацию, и ogl.
 */

/** Что триггер знает об указателе. Пишется на событиях, читается в петле. */
export type PointerProbe = {
  /** Координаты указателя, ЭКРАННЫЕ (clientX/clientY). */
  x: number;
  y: number;
  /** Указатель над карточкой. */
  inside: boolean;
  /** Кнопка/палец нажаты. */
  down: boolean;
  /** Момент нажатия, мс (для отсчёта долгого нажатия). */
  downAt: number;
  /** Накопленный сдвиг с момента нажатия — по нему отличаем скролл от жеста. */
  drift: number;
  /** Природа ввода: палец/перо против мыши. */
  touch: boolean;
};

/**
 * Откуда линза берёт текстуру.
 *
 * ⚠️ Оба источника — то, что человек УЖЕ видит на экране: фото карточки
 * (уже декодированное браузером) или снимок живого чертежа. Тянуть в
 * текстуру что-то своё запрещено — стекло обязано показывать то, что под ним.
 */
export type LensSource =
  /** Фото карточки Collections: берётся её отрисованный <img>. */
  | { kind: "photo"; src: string }
  /** Чертёж Мастерской: офскрин-снимок живого SVG (статичен). */
  | { kind: "svg"; el: SVGSVGElement };

/** Состояние линзы, которое читает шейдер. */
export type LensState = {
  /** Центр линзы в UV карточки (0..1). */
  cx: number;
  cy: number;
  /** Радиус, CSS-px. */
  radius: number;
  zoom: number;
  /** 0 — линзы нет, 1 — проявлена. */
  opacity: number;
};
