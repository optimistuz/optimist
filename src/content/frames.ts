/**
 * КАТАЛОГ — единственный источник товарных данных (CLAUDE.md, «Витрина» п. 2).
 *
 * Тело товара: миллиметры, материал, цвета, наличие по салонам, кадры.
 * Схема и гейт — `catalog/schema.ts` + `scripts/validate-catalog.mjs`
 * (гоняется в `prebuild`: невалидный каталог РОНЯЕТ сборку).
 *
 * ⚠️ ЗДЕСЬ НЕ ВЫДУМЫВАЮТ ТОВАР. Каждая строка — настоящая оправа с полки
 * салона: миллиметры сняты с дужки, материал и цвет — с ярлыка. Правдоподобный
 * артикул, которого нет в наличии, дороже пустого каталога: за него клиент
 * приедет в салон — и не найдёт оправу.
 *
 * ⚠️ Каталог НЕ импортируется маршрутом «/». Критический путь главной
 * израсходован на 4 КБ из 5 (docs/perf-budgets.md) — витрина не имеет права
 * утяжелить главную ни на байт. Импорт — только из маршрутов витрины.
 *
 * ЖИЗНЕННЫЙ ЦИКЛ (см. FRAME_STATUSES):
 *   draft     — тело есть, СВОИХ кадров ещё нет. Не рендерится нигде.
 *   published — кадры сняты и прошли приёмку `ingest-frames.mjs`.
 *   archived  — снят с продажи; в листингах нет, прямая ссылка жива.
 *
 * Артикул становится `published` ТОЛЬКО со своими кадрами. Чужие каталожные
 * снимки брендов (Safilo/Armani/Pierre Cardin) в карточки не идут никогда:
 * они декоративны, aria-hidden и не кликабельны (CLAUDE.md, «Фото и лицензии»).
 *
 * СЕЙЧАС КАТАЛОГ ПУСТ — И ЭТО ЧЕСТНОЕ СОСТОЯНИЕ, А НЕ НЕДОДЕЛКА.
 * Машинное тело готово (схема, гейт, типы, пути к кадрам), а данных нет по
 * двум причинам, и обе — не про код:
 *   1. таблица «артикул → мм → материал → файлы» приходит со съёмкой
 *      (этап 10, шаг 7) — студия ещё не собрана;
 *   2. собственных кадров нет, а без них артикул не может быть `published`.
 * Как только владелец даст список оправ с полки — они лягут сюда черновиками
 * (`draft`) и пройдут мм-санити ещё ДО фотосессии; кадры добавит конвейер.
 */
import type { Frame } from "./catalog/schema.ts";
import { SALON_IDS, type SalonId } from "./catalog/frame.ts";

export const frames: Frame[] = [];

/** Витрина показывает только опубликованное: черновик кадров ещё не имеет. */
export function publishedFrames(): Frame[] {
  return frames.filter((f) => f.status === "published");
}

/**
 * Поиск по slug для PDP. Архивные НАХОДЯТСЯ намеренно: прямая ссылка на
 * снятую с продажи оправу должна открываться (чужие закладки и выдача
 * поисковика не ломаются), просто карточка честно скажет, что её больше нет.
 * Черновики не находятся: их для клиента не существует.
 */
export function frameBySlug(slug: string): Frame | undefined {
  return frames.find((f) => f.slug === slug && f.status !== "draft");
}

export function frameById(id: string): Frame | undefined {
  return frames.find((f) => f.id === id && f.status !== "draft");
}

/** Оправы, которые физически лежат в конкретном салоне. */
export function framesInSalon(salon: SalonId): Frame[] {
  return publishedFrames().filter((f) => f.availability.includes(salon));
}

export { SALON_IDS };
export type { Frame, SalonId };
