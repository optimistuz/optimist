/* ==================================================================
   РАЗМЕЩЕНИЕ ЦЕПОЧКИ KAWASE: под какой размер выделены буферы и как
   из него берётся нормировка радиуса.

   ⚠️ ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Правило «пересобираем только на рост»
   живёт ВНУТРИ рендера (`gl/kawase.ts`), где его нельзя ни спросить,
   ни перебрать: там DOM, WebGL и живой канвас. А следствие у правила
   тяжёлое: размещённый размер РАСХОДИТСЯ с текущим размером канваса,
   и нормировка `ar = размещённый / CSS-ширина` перестаёт быть
   «плотность × клапан». После поворота экрана или ресайза окна она
   принимает значения, которых нет ни в одной статической раскладке
   (пример: цепочка размещена при 342 CSS × 2,0 → 684; контейнер вырос
   до 400 при клапане 0,5 → запрос 400 ≤ 684, пересборки нет, и
   ar = 1,71 — числа, отсутствующего в наборе «плотность × клапан»).
   Именно на этих значениях и проверяется §6-11 в
   `kawase-schedule.test.ts` — перебором ПАР раскладок.

   ⚠️ ПРАВИЛО НЕ КОПИРУЕТСЯ В ТЕСТ. Копия расходится с оригиналом
   молча — проект это уже оплачивал (дубль ширины в конвейере кадров
   разошёлся с реестром, и «десктопный» набор собирался мыльным, пока
   манифест рапортовал об успехе). Поэтому и рендер, и тест зовут
   ОДНУ функцию отсюда.
   ================================================================== */

/** Размер, под который цепочка РАЗМЕЩЕНА (не последний запрошенный). */
export interface AllocSize {
  width: number;
  height: number;
  /** false — буферов ещё нет вовсе (первый запрос пересоберёт всегда). */
  allocated: boolean;
}

export const EMPTY_ALLOC: AllocSize = { width: 0, height: 0, allocated: false };

/**
 * Новый размер размещения после запроса (w, h) — и нужна ли пересборка.
 *
 * ⚠️ ПЕРЕСОБИРАЕМ ТОЛЬКО НА РОСТ. Клапан `renderScale` меняет размер
 * канваса на ходу, и цепочка пересоздавалась на КАЖДУЮ смену: «удалить
 * три FBO и выделить три новых» в самый нагруженный момент, 138 раз за
 * 5,7 минуты (нашёл `hronometrist`). Уменьшение переживаем молча: работа
 * идёт в uv 0…1, поэтому буфер БОЛЬШЕ нужного на геометрию не влияет —
 * только на немного лишнюю память, и это несравнимо дешевле цикла
 * выделений.
 */
export function nextAlloc(
  prev: AllocSize,
  w: number,
  h: number
): AllocSize & { rebuild: boolean } {
  if (prev.allocated && w <= prev.width && h <= prev.height) {
    return { ...prev, rebuild: false };
  }
  return {
    width: Math.max(prev.width, w),
    height: Math.max(prev.height, h),
    allocated: true,
    rebuild: true,
  };
}

/**
 * НОРМИРОВКА РАДИУСА: сколько пикселей БУФЕРА приходится на один
 * CSS-пиксель.
 *
 * ⚠️ Считается из РАЗМЕЩЁННОГО размера, а не из `renderer.dpr`. После
 * шага клапана вниз буфер уменьшился, а уровни остались прежними, и
 * связь «тексел уровня i = 2^(i+1) пикселей буфера» держится только
 * относительно размещённого размера. Взять плотность вместо этого
 * значило бы считать радиус по буферу, которого нет.
 */
export const allocRatio = (allocWidth: number, cssWidth: number): number =>
  cssWidth > 0 ? allocWidth / cssWidth : 0;
