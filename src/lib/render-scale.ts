/**
 * render-scale — страховка канвасов (закон движка №3, CLAUDE.md).
 *
 * Деградирует НЕВИДИМОЕ внутреннее разрешение канваса (renderScale), а НИКОГДА
 * сам эффект. Решение по EMA времени кадра с гистерезисом: если кадры стабильно
 * тяжёлые (EMA > порога) дольше окна удержания — шаг вниз; восстановление
 * медленнее (двойное окно). Итоговое разрешение = min(DPR, 2) × scale.
 *
 * Модуль без React. Первый потребитель — оверлей примерки
 * (`components/ui/frame-overlay.tsx`, этап 7): он сампит время кадра в петле
 * покраски и берёт pixelRatio() вместо голого DPR-капа. Канвасы этапов 5–6
 * (ogl-линза, Kawase-шторка) подключатся так же — sample() в едином тикере,
 * attach() вешает сброс по visibilitychange.
 */
export const MAX_DPR = 2;

export interface RenderScaleOptions {
  /** Нижний предел scale (не деградируем ниже). */
  min?: number;
  /** Шаг деградации/восстановления. */
  step?: number;
  /** Порог «дорогой» покраски, мс РАБОТЫ (8 ≈ половина бюджета кадра 60 fps). */
  slowMs?: number;
  /** Сколько мс подряд держать дорого, чтобы шагнуть вниз. */
  holdMs?: number;
}

export interface RenderScale {
  /**
   * Вызывать каждый кадр.
   *
   * ⚠️ ЗАКОН ЗДЕСЬ — ЗАМКНУТОСТЬ КОНТУРА, а не конкретная величина:
   * `cost` обязан ДВИГАТЬСЯ ОТ ТОГО, ЧЕМ КЛАПАН УПРАВЛЯЕТ. Регулятор, чей
   * датчик не реагирует на его собственные действия, разгоняется в упор и
   * душит разрешение на простаивающем телефоне (так и было на 90-герцевом
   * Galaxy A15). Здоровый кадр обязан давать НОЛЬ — иначе саморазгон.
   *
   * Годятся ровно два датчика (plan.md §8, «Уточнение контракта»):
   *  • СТОИМОСТЬ работы кадра — когда работа синхронна (канвас 2D);
   *  • ПЕРЕРАСХОД над шагом экрана `max(0, dt − step)` — когда работа
   *    уходит на GPU асинхронно и замер вокруг вызова видит только выдачу
   *    команд (ogl-канвасы). `step` ИЗМЕРЯЕТСЯ бегущим минимумом, а не
   *    хардкодится: 16,7 захардкоженные — это тот же баг A15 в новом виде,
   *    у 90-герцевого эталона шаг 11,1.
   *
   * Сырой интервал кадра НЕ ГОДИТСЯ НИКОГДА, и особенно там, где покраска
   * троттлится: он задан герцовкой, а не нагрузкой.
   *
   * ⚠️ Контур замкнут ЛИШЬ ЧАСТИЧНО: в едином тикере на интервал давит
   * работа всей страницы, и понижение разрешения этого канваса чужой
   * тяжёлый кадр не лечит. Поэтому пол обязателен, а клапан, упёршийся
   * в пол, НЕ доказывает вину именно этого канваса.
   */
  sample(cost: number, now: number): number;
  /**
   * Сменить нижний предел на лету.
   *
   * ⚠️ Нужен именно метод, а не проп. Пол зависит от того, ЧТО сейчас на
   * канвасе: у шторки симулятора при |D| ≥ 1,5 дптр слой и так размыт —
   * снижать невидимое разрешение честно (0,5); при почти резком слое тот же
   * пол замылил бы сам эффект (запрет §3-3) и провалил бы приёмку шва.
   * Через проп это не сделать: `minScale` уходит в `createRenderScale`
   * внутри эффекта, чей deps-список его содержит, — реактивное значение
   * ПЕРЕСОЗДАВАЛО БЫ GL-КОНТЕКСТ каждый раз, когда палец пересекает порог
   * посреди перетаскивания (поймал `dirizher` на брифе, до написания кода).
   */
  setMin(v: number): void;
  /** Сбросить временные аккумуляторы (scale «липкий», не сбрасывается). */
  reset(): void;
  /** Повесить сброс по visibilitychange (вызывает потребитель-канвас). */
  attach(): void;
  detach(): void;
  readonly scale: number;
  /** Итоговый pixelRatio канваса: min(DPR, 2) × scale. */
  pixelRatio(): number;
}

/**
 * ДАТЧИК «ПЕРЕРАСХОД НАД ШАГОМ ЭКРАНА» — для канвасов, чья работа уходит на
 * GPU асинхронно (ogl). Отдельной функцией, потому что закон о замкнутости
 * контура обязан ПРОВЕРЯТЬСЯ, а не декларироваться: клапан этапа 5 был
 * подключён, покрыт 18 юнит-проверками — и слеп, потому что датчик мерил
 * выдачу GL-команд вместо цены кадра.
 *
 * Здоровый кадр даёт РОВНО НОЛЬ: шаг экрана вычитается. Поэтому саморазгон
 * структурно невозможен, а порог восстановления достижим.
 */
export interface FrameOveruse {
  /** Интервал между двумя НАРИСОВАННЫМИ кадрами → перерасход, мс. */
  push(dt: number): number;
  /** Кадр пропущен: следующий интервал содержит паузу, а не работу. */
  gap(): void;
  /** Текущая оценка шага экрана, мс (0 — ещё не измерен). */
  readonly step: number;
}

export function createFrameOveruse(): FrameOveruse {
  let step = 0;
  let armed = false;

  return {
    push(dt: number): number {
      if (!armed) {
        // Первый кадр после паузы: интервал недостоверен, но шаг уточнить можно.
        armed = true;
        return 0;
      }
      // <4 мс — сдвоенный колбэк (о нагрузке не говорит).
      //
      // ⚠️ ВЕРХНИЙ ПРЕДЕЛ ОТСЕКАЕТ ПАУЗЫ, А НЕ ТЯЖЁЛЫЕ КАДРЫ. Сперва здесь
      // стояло 100 мс — и на стенде с придушенным процессором, где интервал
      // держался на 383 мс, датчик отбрасывал АБСОЛЮТНО ВСЁ и клапан не
      // шагал ни разу. Это тот же дефект, за который отсечка 250 мс уже
      // ловилась в этапе 7: предохранитель слепит прибор ровно в той полосе,
      // ради которой прибор и стоит. 10 fps — это ещё работа; настоящие
      // паузы (фон вкладки, точка останова) отсекаются признаком пропуска
      // кадра и `visibilitychange`, а не порогом.
      if (!(dt >= 4 && dt <= 1000)) return 0;
      // Бегущий минимум с медленным отпусканием вверх: сам находит
      // 16,7 / 11,1 / 8,3 и переживает смену режима экрана. ⚠️ Хардкод 16,7
      // здесь был бы багом A15 в новом виде — у 90-герцевого эталона 11,1.
      step = step === 0 ? dt : Math.min(step * 1.0008, dt);
      return Math.max(0, dt - step);
    },
    gap() {
      armed = false;
    },
    get step() {
      return step;
    },
  };
}

export function createRenderScale(opts: RenderScaleOptions = {}): RenderScale {
  let min = opts.min ?? 0.5;
  const step = opts.step ?? 0.15;
  // Пороги — в миллисекундах РАБОТЫ на кадр. Бюджет кадра при 60 fps — 16,7 мс,
  // и он делится с детекцией, композитором и остальной страницей: покраска
  // дороже половины бюджета — настоящая перегрузка, а не всплеск.
  const slowMs = opts.slowMs ?? 8;
  const holdMs = opts.holdMs ?? 3000; // 3 с подряд
  // ⚠️ Порог восстановления обязан быть ДОСТИЖИМ. Прежняя формула (0,75 от
  // порога) при измерении по wall-clock давала 14,25 мс при минимально
  // возможном dt 16,67 мс — условие не выполнялось НИКОГДА, и любая
  // деградация, включая ложную, была необратима (нашёл `hronometrist`).
  // Дешёвая покраска канваса стоит 1–3 мс, так что 60 % порога берётся.
  const fastMs = slowMs * 0.6;
  const recoverMs = holdMs * 2; // восстановление медленнее деградации

  // Стартовая оценка — дешёвая покраска, а не период кадра: EMA теперь
  // измеряет работу.
  let ema = 2;
  let scale = 1;
  let slowSince = 0;
  let fastSince = 0;

  const round = (n: number) => Math.round(n * 100) / 100;

  function reset() {
    ema = 2;
    slowSince = 0;
    fastSince = 0;
    // scale НЕ сбрасываем — деградация «липкая» до честного восстановления
  }

  const onVis = () => {
    // Вкладку свернули → кадры-выбросы; на возврате чистим аккумуляторы,
    // чтобы простой не выдал ложную деградацию.
    if (typeof document !== "undefined" && !document.hidden) reset();
  };

  function sample(cost: number, now: number): number {
    // Аномальные замеры (точка останова, вытеснение потока, свёрнутая вкладка)
    // игнорируем: это не стоимость покраски, а провал в планировщике.
    //
    // ⚠️ Порог 500, а НЕ 250. При замере интервалов 250 мс отсекали ровно ту
    // полосу, ради которой клапан существует: под тяжёлым троттлингом ВСЕ
    // кадры длиннее 250 мс, и клапан становился инертен там, где нужнее всего
    // (нашёл `fizik`). Со стоимостью работы запас нужен тот же: на слабом
    // устройстве под нагрузкой честная покраска доходит до сотен мс, и
    // отбрасывать её как «аномалию» значит слепнуть в перегрузке.
    if (!(cost >= 0) || cost > 500) {
      slowSince = 0;
      fastSince = 0;
      return scale;
    }
    ema = ema * 0.95 + cost * 0.05;

    if (ema > slowMs) {
      fastSince = 0;
      if (slowSince === 0) slowSince = now;
      else if (now - slowSince >= holdMs && scale > min) {
        scale = Math.max(min, round(scale - step));
        slowSince = now; // один шаг за окно удержания
      }
    } else if (ema < fastMs) {
      slowSince = 0;
      if (fastSince === 0) fastSince = now;
      else if (now - fastSince >= recoverMs && scale < 1) {
        scale = Math.min(1, round(scale + step));
        fastSince = now;
      }
    } else {
      // нейтральная зона — не копим ни деградацию, ни восстановление
      slowSince = 0;
      fastSince = 0;
    }
    return scale;
  }

  return {
    sample,
    reset,
    setMin(v: number) {
      min = Math.min(1, Math.max(0.1, v));
      // Уже уехавший ниже нового пола scale подтягиваем сразу: иначе кадр
      // остался бы мыльнее, чем разрешено, до следующего шага вверх.
      if (scale < min) scale = min;
    },
    attach() {
      if (typeof document !== "undefined")
        document.addEventListener("visibilitychange", onVis);
    },
    detach() {
      if (typeof document !== "undefined")
        document.removeEventListener("visibilitychange", onVis);
    },
    get scale() {
      return scale;
    },
    pixelRatio() {
      const dpr =
        typeof window !== "undefined" ? window.devicePixelRatio || 1 : 1;
      return Math.min(dpr, MAX_DPR) * scale;
    },
  };
}
