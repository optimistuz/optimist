/* ==================================================================
   РАСПИСАНИЕ ЦЕПОЧКИ DUAL-KAWASE: сколько уровней брать и с каким
   разъездом выборок, чтобы получить заданный радиус.

   ⚠️ РАСПИСАНИЕ ПОСТРОЕНО НА ИЗМЕРЕННОЙ ТАБЛИЦЕ, НЕ НА ФОРМУЛЕ.
   Аналитическая модель (пол цепочки из дисперсий билинейных чтений,
   якорь TARGET_K) не сошлась ЧЕТЫРЕ раза подряд: пол третьей ступени
   она занижала в 3,25 раза, и «уйти глубже» всегда означало «стать
   мутнее», сколько ни правь константы. Юнит-тест при этом был зелёным —
   он подставлял ту же неверную формулу по обе стороны границы и
   доказывал лишь самосогласованность модели, пока браузер показывал
   скачки на 8 границах из 8. Урок вынесен в канон: непрерывность
   доказывается конструкцией НА ИЗМЕРЕННОМ ПОЛЕ.

   Таблица `LEVEL_REQ` снята прибором `scripts/probe-kawase.mjs` (фаза
   `cal`): каждой паре (ступень, разъезд) сопоставлен ЭКВИВАЛЕНТНЫЙ
   РАДИУС честного CSS-`blur(r)` — сырое σ² цепочки обращено через сырую
   шкалу фолбэка ТОГО ЖЕ прогона, так что систематика прибора входит в
   оба числа и сокращается. Годность таблицы сторожит гейт согласия двух
   эталонов разной резкости (σ₀ = 4 и 10), сформулированный в ПРЯМУЮ
   сторону — по радиусу, который видит человек, а не по разъезду,
   внутренней ручке машинерии, плохо обусловленной у пола ступени
   (решение dirizher, 30 июля). Константа генерируется
   `scripts/gen-kawase-table.mjs` из JSON прибора — руками не набирается
   и не правится.

   Здесь по-прежнему ЧИСТАЯ ФУНКЦИЯ без DOM: свойства доказываются
   арифметикой в `kawase-schedule.test.ts` (`npm run test:lib`), включая
   негативный контроль по прежней аналитике.
   ================================================================== */

// Прогонов учтено: 4 (эталоны σ₀ = 4 и 10, основной и глубокий гриды,
// 30 июля 2026). Сгенерировано scripts/gen-kawase-table.mjs — руками
// не править; пересъёмка: probe-kawase cal → gen-kawase-table.
export const LEVEL_REQ: readonly (readonly (readonly [number, number])[])[] = [
  /* lv 1 */
  [[0, 1.697], [0.3, 1.899], [0.45, 2.121], [0.6, 2.375], [0.75, 2.703], [0.9, 3.073], [1.05, 3.419], [1.2, 3.832], [1.35, 4.21], [1.5, 4.588], [1.65, 4.981]],
  /* lv 2 */
  [[0, 4.374], [0.3, 4.689], [0.45, 5.341], [0.6, 6.195], [0.75, 7.08], [0.9, 8.172], [1.05, 9.165], [1.2, 10.171], [1.35, 11.284], [1.5, 12.387], [1.65, 13.487]],
  /* lv 3 */
  [[0, 9.409], [0.3, 9.964], [0.45, 11.209], [0.6, 13.046], [0.75, 14.783], [0.9, 17.268], [1.05, 19.498], [1.2, 21.442], [1.35, 23.907], [1.5, 26.19], [1.65, 28.613]],
  /* lv 4 */
  [[0, 18.844], [0.3, 19.875], [0.45, 22.762], [0.6, 26.355], [0.75, 30.015], [0.9, 34.971], [1.05, 39.734], [1.2, 43.626]],
  /* lv 5 */
  [[0, 34.695], [0.45, 43.809]],
];

/**
 * ПОТОЛОК РАЗЪЕЗДА — ПО СТУПЕНЯМ, из двух независимых проб.
 *
 * lv1 = 1,45. Требуется 1,44, чтобы дотянуться до пола ступени 2, —
 * запас 1 %. Кольцевая проба на крест (фаза `cross`) даёт lv1 всего 0,5,
 * НО решает не она: в дыре 2,4…4,3 px радиуса кто-то обязан рисовать, и
 * фаза `match` сравнила ОБОИХ кандидатов с честным blur(4,3) на реальном
 * фото — lv1@1,42 честнее lv2 на полу И по средней |Δ| (4,97 против
 * 5,73), И по худшему блоку 16×16 (18,0 против 19,7). Это argmin по
 * измеренным кандидатам, порога-константы здесь нет (решение dirizher).
 *
 * lv2–5 = 1,4 — минимум из измеренных кольцевой пробой потолков
 * (1,4 / 1,6 / 1,6 / 1,4); потребность там ≤ 0,91, запас с избытком.
 */
export const OFFSET_MAX: readonly number[] = [1.45, 1.4, 1.4, 1.4, 1.4];

/** Ломаная по измеренным точкам; вне диапазона — крайнее значение (НЕ
    экстраполяция: за последней измеренной точкой знания нет). */
function interpClamped(
  pts: readonly (readonly [number, number])[],
  x: number,
  ix: 0 | 1,
  iy: 0 | 1
): number {
  if (x <= pts[0][ix]) return pts[0][iy];
  for (let i = 1; i < pts.length; i += 1) {
    if (x <= pts[i][ix]) {
      const t = (x - pts[i - 1][ix]) / (pts[i][ix] - pts[i - 1][ix]);
      return pts[i - 1][iy] + t * (pts[i][iy] - pts[i - 1][iy]);
    }
  }
  return pts[pts.length - 1][iy];
}

/** Эквивалентный радиус ступени `lv` при разъезде `offset` (px буфера). */
export const levelRadius = (lv: number, offset: number): number =>
  interpClamped(LEVEL_REQ[lv - 1], offset, 0, 1);

/** Пол ступени: её эквивалентный радиус при нулевом разъезде. */
export const levelFloor = (lv: number): number => LEVEL_REQ[lv - 1][0][1];

/** Потолок ступени: радиус на её потолке разъезда, ограниченный ИЗМЕРЕННЫМ
    диапазоном — сверх последней точки таблица молчит, и мы вместе с ней. */
export const levelCeil = (lv: number): number => {
  const pts = LEVEL_REQ[lv - 1];
  const maxMeasured = pts[pts.length - 1][0];
  return levelRadius(lv, Math.min(OFFSET_MAX[lv - 1], maxMeasured));
};

/** Радиус, ниже которого цепочка не умеет: пол первой ступени.
    Ниже него работает рампа подмешивания резкого источника. */
export const minRadius = (): number => levelFloor(1);

export type ChainPlan = {
  /** Глубина цепочки; 0 — цепочка выключена, источник идёт прямо на выход. */
  lv: number;
  /** Разъезд выборок в текселях приёмника. */
  offset: number;
  /** Доля результата цепочки против резкого источника (рампа у нуля). */
  mix: number;
  /** true — радиус больше того, что цепочка может дать при данном `levels`. */
  saturated: boolean;
};

/**
 * Выбрать глубину и разъезд под радиус `rBuf` (в пикселях БУФЕРА).
 *
 * Ступень — НАИМЕНЬШАЯ, чей потолок дотягивается до цели; разъезд —
 * обращение измеренной кривой этой ступени в точке цели.
 *
 * ⚠️ НЕПРЕРЫВНОСТЬ НА ГРАНИЦАХ — ПО ИЗМЕРЕНИЮ, а не по формуле: в точке
 * переключения ступень `lv` на потолке и ступень `lv+1` на своём разъезде
 * дают ОДИН И ТОТ ЖЕ измеренный эквивалентный радиус — это буквально
 * соседние строки одной таблицы, снятой одним прибором. Тест сверяет
 * отсутствие дыр (потолок каждой ступени не ниже пола следующей) и
 * гладкость выданного радиуса по всему ходу.
 */
export function planChain(rBuf: number, levels: number): ChainPlan {
  if (!(rBuf > 0) || levels < 1) return { lv: 0, offset: 0, mix: 0, saturated: false };
  const maxLv = Math.min(levels, LEVEL_REQ.length);

  const rMin = minRadius();
  const mix = Math.min(1, rBuf / rMin);
  if (rBuf <= rMin) {
    // Слабее собственного пола цепочка не умеет — разницу добирает
    // подмешивание резкого источника (uMix в OUT-проходе).
    return { lv: 1, offset: 0, mix, saturated: false };
  }

  for (let lv = 1; lv <= maxLv; lv += 1) {
    if (rBuf <= levelCeil(lv) + 1e-9) {
      // Обращение измеренной кривой: (радиус → разъезд).
      const offset = rBuf <= levelFloor(lv) ? 0 : interpClamped(LEVEL_REQ[lv - 1], rBuf, 1, 0);
      return { lv, offset, mix: 1, saturated: false };
    }
  }

  // Глубже некуда: радиус больше достижимого. Исход ОБЪЯВЛЕН, а не
  // заклампован молча — молчаливый кламп уже прятал потолок на телефоне.
  const lv = maxLv;
  const pts = LEVEL_REQ[lv - 1];
  return {
    lv,
    offset: Math.min(OFFSET_MAX[lv - 1], pts[pts.length - 1][0]),
    mix: 1,
    saturated: true,
  };
}
