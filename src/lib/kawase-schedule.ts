// Прогонов учтено: 4 (эталоны σ₀ = 4 и 10, основной и глубокий гриды,
// 31 июля 2026, ЯДРО lv1 С UP-ПРОХОДОМ). Сгенерировано
// scripts/gen-kawase-table.mjs — руками не править; пересъёмка:
// probe-kawase cal → gen-kawase-table. Ветви lv2–5 воспроизвели таблицу
// 30 июля в точности (контроль пересъёмки: смена ядра lv1 чужого не задела).
export const LEVEL_REQ: readonly (readonly (readonly [number, number])[])[] = [
  /* lv 1 (DOWN→UP→OUT): плато пола исчезло — UP работает с первого разъезда */
  [[0, 1.697], [0.15, 2.305], [0.3, 2.893], [0.45, 3.393], [0.6, 4.059], [0.75, 4.69], [0.9, 5.275], [1.05, 5.962], [1.2, 6.884], [1.35, 7.696], [1.5, 8.396], [1.65, 9.169]],
  /* lv 2 */
  [[0, 4.374], [0.3, 4.689], [0.45, 5.341], [0.6, 6.195], [0.75, 7.08], [0.9, 8.172], [1.05, 9.165], [1.2, 10.171], [1.35, 11.284], [1.5, 12.387], [1.65, 13.487]],
  /* lv 3 */
  [[0, 9.409], [0.3, 9.964], [0.45, 11.209], [0.6, 13.046], [0.75, 14.783], [0.9, 17.268], [1.05, 19.498], [1.2, 21.442], [1.35, 23.907], [1.5, 26.19], [1.65, 28.613]],
  /* lv 4 */
  [[0, 18.844], [0.3, 19.875], [0.45, 22.762], [0.6, 26.355], [0.75, 30.015], [0.9, 34.971], [1.05, 39.734], [1.2, 43.626]],
  /* lv 5 */
  [[0, 34.695], [0.45, 43.809]],
];

/**
 * ПОТОЛОК РАЗЪЕЗДА — ПО СТУПЕНЯМ, из кольцевой пробы на крест (фаза
 * `cross`), пересъёмка 31 июля на ядре lv1 С UP-ПРОХОДОМ.
 *
 * lv1 = 1,2. Звезда, державшая старое ядро на 0,5, отступила: UP-проход
 * сливает четыре тапа (0,5→6,3 %, 0,8→3,9 %, 1,2→12,2 %, дальше >15 %).
 * Требуется 0,68, чтобы дотянуться до пола ступени 2, — запас 76 %.
 * Прежняя запись «1,45 при потребности 1,44, санкция match» относилась
 * к ядру без UP и умерла вместе с ним.
 *
 * lv2–5 = 1,4 — минимум из измеренных потолков (1,4 / 1,6 / 1,6 / 1,4);
 * потребность там ≤ 0,91, запас с избытком.
 */
export const OFFSET_MAX: readonly number[] = [1.2, 1.4, 1.4, 1.4, 1.4];

/** Ломаная по измеренным точкам; вне диапазона — крайнее значение (НЕ
    экстраполяция: за последней измеренной точкой знания нет). */
function interpClamped(
  pts: readonly (readonly [number, number])[],
  x: number,
  ix: 0 | 1,
  iy: 0 | 1
): number {
  if (x <= pts[0][ix]) return pts[0][iy];
  for (let i = 1; i < pts.length; i += 1) {
    if (x <= pts[i][ix]) {
      const t = (x - pts[i - 1][ix]) / (pts[i][ix] - pts[i - 1][ix]);
      return pts[i - 1][iy] + t * (pts[i][iy] - pts[i - 1][iy]);
    }
  }
  return pts[pts.length - 1][iy];
}

/** Эквивалентный радиус ступени `lv` при разъезде `offset` (px буфера). */
export const levelRadius = (lv: number, offset: number): number =>
  interpClamped(LEVEL_REQ[lv - 1], offset, 0, 1);

/** Пол ступени: её эквивалентный радиус при нулевом разъезде. */
export const levelFloor = (lv: number): number => LEVEL_REQ[lv - 1][0][1];

/** Потолок ступени: радиус на её потолке разъезда, ограниченный ИЗМЕРЕННЫМ
    диапазоном — сверх последней точки таблица молчит, и мы вместе с ней. */
export const levelCeil = (lv: number): number => {
  const pts = LEVEL_REQ[lv - 1];
  const maxMeasured = pts[pts.length - 1][0];
  return levelRadius(lv, Math.min(OFFSET_MAX[lv - 1], maxMeasured));
};

/** Радиус, ниже которого цепочка не умеет: пол первой ступени.
    Ниже него работает рампа подмешивания резкого источника. */
export const minRadius = (): number => levelFloor(1);

/**
 * ТОЧКИ ПЕРЕКЛЮЧЕНИЯ — ИЗМЕРЕННЫЕ, а не «на потолке ступени».
 *
 * σ²-равенство строит ПЕРЕКРЫТИЕ соседних ступеней, но σ² — один момент и
 * ФОРМУ ядра не видит: на стыке двух ступеней с равной дисперсией картинка
 * может щёлкнуть (поймано пиксельной таблицей 30 июля: 4,8 при рядовых
 * 0,84). Где именно щёлкать — решает argmin |A−B| фазы `seam` прибора:
 * радиус, на котором два ядра НАИМЕНЕЕ различимы пикселями. Замер 31 июля:
 * argmin у всех трёх пар — на КРАЮ перекрытия («переключайся на потолке»),
 * плато нет. Поэтому `null` — это ИЗМЕРЕННЫЙ выбор, а не умолчание.
 *
 * Инварианты (закреплены тестом): floor(lv+1) ≤ SWITCH_R[lv] ≤ ceil(lv).
 */
export const SWITCH_R: readonly (number | null)[] = [null, null, null, null, null];

/** Верх использования ступени: измеренная точка переключения или потолок. */
const levelTop = (lv: number): number => {
  const sw = SWITCH_R[lv - 1];
  const ceil = levelCeil(lv);
  return sw !== null && sw !== undefined ? Math.min(sw, ceil) : ceil;
};

/**
 * ⚠️ ЗАКРЫВАЕТ ЛИ СТУПЕНЬ ЦЕЛУЮ ПОЛОСУ ПОДПИСИ [lo, hi] (px буфера).
 *
 * Смена глубины цепочки стоит ~4× рядового шага ВСЕГДА — это измерено на
 * пяти границах, обеих плотностях, на ступенях с UP-проходом и без
 * (31 июля). Значит спрятать щелчок внутри подписи нельзя ничем; его можно
 * только ВЫНЕСТИ ТУДА, ГДЕ ОН ЗАКОННЫЙ — на границу смены `aria-valuenow`,
 * где и так меняется число и звучит гаптика. Тогда §6-11 выполняется ПО
 * ПОСТРОЕНИЮ: внутри одной подписи ядро одно, радиус добирается только
 * непрерывным разъездом.
 *
 * ⚠️ Ступень должна покрывать полосу С ОБЕИХ сторон: потолком — верх,
 * полом — низ. Недобор снизу законен ТОЛЬКО у первой ступени: там его
 * закрывает рампа подмешивания резкого источника (`mix`), а глубже рампы
 * нет и «пол выше цели» означало бы «мутнее, чем просили».
 *
 * ⚠️ ЭКСПОРТИРУЕТСЯ РАДИ ТЕСТА, и это осознанно: тест обязан спрашивать
 * САМ предикат, а не его копию. Копия расходится с оригиналом молча —
 * проект это уже оплачивал (дубль ширины в конвейере кадров).
 */
export const levelCoversBand = (lv: number, lo: number, hi: number): boolean =>
  levelTop(lv) >= hi - 1e-9 && (lv === 1 || levelFloor(lv) <= lo + 1e-9);

export type ChainPlan = {
  /** Глубина цепочки; 0 — цепочка выключена, источник идёт прямо на выход. */
  lv: number;
  /** Разъезд выборок в текселях приёмника. */
  offset: number;
  /** Доля результата цепочки против резкого источника (рампа у нуля). */
  mix: number;
  /** true — радиус больше того, что цепочка может дать при данном `levels`. */
  saturated: boolean;
};

/**
 * Выбрать глубину и разъезд под радиус `rBuf` (в пикселях БУФЕРА).
 *
 * Ступень — НАИМЕНЬШАЯ, чей потолок дотягивается до цели; разъезд —
 * обращение измеренной кривой этой ступени в точке цели.
 *
 * ⚠️ НЕПРЕРЫВНОСТЬ НА ГРАНИЦАХ — ПО ИЗМЕРЕНИЮ, а не по формуле: в точке
 * переключения ступень `lv` на потолке и ступень `lv+1` на своём разъезде
 * дают ОДИН И ТОТ ЖЕ измеренный эквивалентный радиус — это буквально
 * соседние строки одной таблицы, снятой одним прибором. Тест сверяет
 * отсутствие дыр (потолок каждой ступени не ниже пола следующей) и
 * гладкость выданного радиуса по всему ходу.
 */
export function planChain(
  rBuf: number,
  levels: number,
  /**
   * ПОЛОСА ПОДПИСИ [lo, hi] в пикселях буфера — диапазон радиусов, которым
   * соответствует ТЕКУЩЕЕ значение `aria-valuenow`. Когда она задана,
   * глубина выбирается ОДНА НА ВСЮ ПОЛОСУ (см. `levelCoversBand`), и
   * переключения внутри подписи не случается ни при каком радиусе.
   * Без неё выбор идёт по факту — прежнее поведение.
   */
  band?: readonly [number, number]
): ChainPlan {
  if (!(rBuf > 0) || levels < 1) return { lv: 0, offset: 0, mix: 0, saturated: false };
  const maxLv = Math.min(levels, LEVEL_REQ.length);

  const rMin = minRadius();
  const mix = Math.min(1, rBuf / rMin);
  if (rBuf <= rMin) {
    // Слабее собственного пола цепочка не умеет — разницу добирает
    // подмешивание резкого источника (uMix в OUT-проходе).
    return { lv: 1, offset: 0, mix, saturated: false };
  }

  // Разъезд ВСЕГДА считается по фактическому радиусу: полоса управляет
  // только выбором глубины, иначе внутри подписи размытие стало бы
  // ступенчатым — ровно то квантование, от которого ушёл шаг 1.
  const offsetFor = (lv: number) =>
    rBuf <= levelFloor(lv) ? 0 : interpClamped(LEVEL_REQ[lv - 1], rBuf, 1, 0);

  if (band) {
    const lo = Math.max(0, Math.min(band[0], band[1]));
    const hi = Math.max(band[0], band[1]);
    for (let lv = 1; lv <= maxLv; lv += 1) {
      if (levelCoversBand(lv, lo, hi)) return { lv, offset: offsetFor(lv), mix: 1, saturated: false };
    }
    // Ни одна ступень не покрывает полосу целиком — падаем на выбор по
    // факту. Молчаливо: это не ошибка радиуса, а исчерпание цепочки на
    // верхнем краю хода; инвариант «полоса покрыта» стережёт юнит-тест по
    // всем раскладкам, и его провал — сигнал раньше, чем кадр.
  }

  for (let lv = 1; lv <= maxLv; lv += 1) {
    // Последняя ступень дорабатывает до своего ПОТОЛКА, даже если точка
    // переключения назначена: переключаться ей больше не на кого.
    const top = lv === maxLv ? levelCeil(lv) : levelTop(lv);
    if (rBuf <= top + 1e-9) {
      return { lv, offset: offsetFor(lv), mix: 1, saturated: false };
    }
  }

  // Глубже некуда: радиус больше достижимого. Исход ОБЪЯВЛЕН, а не
  // заклампован молча — молчаливый кламп уже прятал потолок на телефоне.
  const lv = maxLv;
  const pts = LEVEL_REQ[lv - 1];
  return {
    lv,
    offset: Math.min(OFFSET_MAX[lv - 1], pts[pts.length - 1][0]),
    mix: 1,
    saturated: true,
  };
}
