/* ==================================================================
   РАСПИСАНИЕ ЦЕПОЧКИ DUAL-KAWASE: сколько уровней брать и с каким
   разъездом выборок, чтобы получить заданный радиус.

   ⚠️ ЗАЧЕМ ЭТО ВЫНЕСЕНО ОТДЕЛЬНОЙ ЧИСТОЙ ФУНКЦИЕЙ. Расписание — это
   то место, где симулятор дважды соврал молча, и оба раза дефект был
   невидим глазами (маскируется размытием), невидим типами и невидим
   линтером:

   1. Разъезд считался как `radius / 2^(lv+1)` — формула ОДНОГО прохода,
      тогда как проходов `2·lv−1`. На каждой смене уровня картинка
      прыгала: резкость падала на 8–55 % за шаг ползунка в сотую долю
      пикселя, ВНУТРИ одной подписи «−3 дптр».
   2. Уровень выбирался степенью двойки, без оглядки на то, способен ли
      он вообще дать нужное размытие. При rBuf = 8 уровень 3 физически
      не мог: его собственный пол уже больше цели.

   Здесь это проверяется АРИФМЕТИКОЙ, без Chrome и без дев-сервера
   (`src/lib/kawase-schedule.test.ts`, `npm run test:lib`). Непрерывность
   доказывается КОНСТРУКЦИЕЙ: в точке переключения оба уровня дают ровно
   целевую дисперсию — см. `chainVariance`.
   ================================================================== */

/**
 * Дисперсия ядра по одной оси у прохода DOWN, в единицах `uOffset²`.
 * Считана из весов шейдера: центр весом 4 и четыре диагонали весом 1.
 */
const V_DOWN = 0.5;
/**
 * То же у прохода UP: восемь выборок с плечами до 2·o.
 * ⚠️ В 2,67 РАЗА ШИРЕ, чем у DOWN. Первая калибровка считала проходы
 * равными — этого не хватило, скачки остались.
 */
const V_UP = 4 / 3;

/** Σ квадратов текселов приёмников по n проходам: тексел уровня i = 2^(i+2). */
const sumTargets = (n: number) => (n <= 0 ? 0 : (16 * (Math.pow(4, n) - 1)) / 3);

/**
 * Множитель при `uOffset²` в полной дисперсии цепочки глубины `lv`:
 * `lv` проходов DOWN и `lv−1` проходов UP, каждый со своим текселом.
 */
export const offsetGain = (lv: number) =>
  V_DOWN * sumTargets(lv) + V_UP * sumTargets(lv - 1);

/**
 * ПОЛ ЦЕПОЧКИ — дисперсия, которая есть при `uOffset = 0` и от разъезда
 * НЕ зависит вовсе: билинейная фильтрация при каждом чтении текстуры.
 *
 * ⚠️ Именно её отсутствие в модели и породило скачки. Пол растёт с
 * глубиной (уровень читает всё более крупные тексели), поэтому «уйти
 * глубже» — это всегда «стать мутнее», сколько ни уменьшай разъезд.
 * Слагаемые: чтения источника каждым DOWN, чтения более грубого уровня
 * каждым UP и финальное чтение нулевого уровня проходом OUT.
 */
export function chainFloor(lv: number): number {
  if (lv <= 0) return 0;
  let sum = 0;
  for (let i = 0; i < lv; i += 1) {
    const srcTexel = i === 0 ? 1 : Math.pow(2, i + 1); // DOWN читает источник
    sum += srcTexel * srcTexel;
  }
  for (let i = 0; i <= lv - 2; i += 1) {
    const srcTexel = Math.pow(2, i + 3); // UP читает уровень покрупнее
    sum += srcTexel * srcTexel;
  }
  sum += 16; // OUT читает нулевой уровень (тексел 4)
  return sum / 12;
}

/** Полная дисперсия ядра цепочки: пол плюс вклад разъезда. */
export const chainVariance = (lv: number, offset: number) =>
  lv <= 0 ? 0 : chainFloor(lv) + offsetGain(lv) * offset * offset;

/**
 * ЯКОРЬ ЕДИНИЦЫ РАДИУСА — единственный свободный параметр модели.
 * Исторически «радиус» означал разъезд на текселе нулевого уровня:
 * `offset = rBuf / 4`, то есть дисперсия `rBuf²/16 · 8 = rBuf²/2`.
 * ⚠️ Появится нужда во втором свободном параметре (поправка на уровень) —
 * значит модель не сошлась, и это повод остановиться, а не подкрутить.
 */
export const TARGET_K = 0.5;
export const targetVariance = (rBuf: number) => TARGET_K * rBuf * rBuf;

/**
 * ПОТОЛОК РАЗЪЕЗДА. За ним четыре выборки Kawase перестают сливаться
 * в размытие и дают видимый крест — то есть эффект деградирует сам,
 * что запрещено §3-3. Значение назначается ПРОБОЙ НА АРТЕФАКТ, а не
 * вкусом; здесь оно живёт одной константой, чтобы проба могла его
 * двигать в одном месте.
 */
export const OFFSET_MAX = 1;

/** Радиус (в пикселях буфера), ниже которого цепочка не умеет: её пол. */
export const minRadius = (lv = 1) => Math.sqrt(chainFloor(lv) / TARGET_K);

export type ChainPlan = {
  /** Глубина цепочки; 0 — цепочка выключена, источник идёт прямо на выход. */
  lv: number;
  /** Разъезд выборок в текселях приёмника. */
  offset: number;
  /** Доля результата цепочки против резкого источника (рампа у нуля). */
  mix: number;
  /** true — радиус больше того, что цепочка может дать при данном `levels`. */
  saturated: boolean;
};

/**
 * Выбрать глубину и разъезд под радиус `rBuf` (в пикселях БУФЕРА).
 *
 * Уровень — НАИМЕНЬШИЙ, удовлетворяющий ОБОИМ ограничениям:
 *   1) его пол ниже цели (иначе он физически не даст нужное размытие);
 *   2) разъезд не выше потолка (иначе вылезет крест четырёх тапов).
 *
 * ⚠️ ИЗ ЭТОГО НЕПРЕРЫВНОСТЬ СЛЕДУЕТ ПО ПОСТРОЕНИЮ, а не по подгонке:
 * в точке переключения уровень `lv` работает на потолке разъезда и даёт
 * полную дисперсию ровно `targetVariance`, а уровень `lv+1` на той же
 * цели даёт свой разъезд из того же уравнения — и ту же дисперсию.
 * Где бы точка переключения ни оказалась, слева и справа от неё ядро
 * одинаково.
 */
export function planChain(rBuf: number, levels: number): ChainPlan {
  if (!(rBuf > 0) || levels < 1) return { lv: 0, offset: 0, mix: 0, saturated: false };

  const target = targetVariance(rBuf);
  const floor1 = chainFloor(1);

  // Ниже собственного пола цепочки размытия не бывает — там работает
  // рампа подмешивания резкого источника, и это НЕ константа «4 px»,
  // а тот же пол, выраженный в радиусе.
  const rMin = minRadius(1);
  const mix = Math.min(1, rBuf / rMin);
  if (target <= floor1) {
    // Цепочка на минимуме; всю разницу добирает подмешивание источника.
    return { lv: 1, offset: 0, mix, saturated: false };
  }

  for (let lv = 1; lv <= levels; lv += 1) {
    const floor = chainFloor(lv);
    if (floor >= target) continue; // уровень не дотянет — он уже мутнее цели
    // ⚠️ ПОДКОРЕННОЕ ЗАЩИЩЕНО: отрицательное дало бы NaN в юниформе, то есть
    // чёрный или мусорный кадр БЕЗ единой ошибки в консоли.
    const offset = Math.sqrt(Math.max(0, target - floor) / offsetGain(lv));
    if (offset <= OFFSET_MAX) return { lv, offset, mix, saturated: false };
  }

  // Цепочка кончилась: глубже некуда, радиус больше достижимого.
  // ⚠️ Исход ОБЪЯВЛЕН, а не заклампован молча: молчаливый кламп — это
  // ровно то, из-за чего «честные −6 дптр» упирались в потолок на
  // эталонном телефоне и никто этого не видел.
  const lv = levels;
  const offset = Math.sqrt(
    Math.max(0, targetVariance(rBuf) - chainFloor(lv)) / offsetGain(lv)
  );
  return { lv, offset, mix, saturated: true };
}
