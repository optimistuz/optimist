/**
 * ГАПТИКА — единственная точка вибрации во всём проекте (CLAUDE.md,
 * «Мобильный паритет»): feature-detect, троттлинг 40 мс, словарь из трёх
 * значений. Прямой вызов `navigator.vibrate` где-либо ещё — нарушение:
 * разрозненные длительности превращают тактильный язык в шум, а троттлинг,
 * живущий в каждом компоненте отдельно, не общий — и телефон начинает
 * дребезжать, когда два эффекта срабатывают рядом.
 *
 * СЛОВАРЬ (длительности — закон, не параметр вызова):
 *   snap    10 мс — щелчок ступени, снап позиции;
 *   choice  20 мс — выбор сделан (чипс, силуэт);
 *   success 30 мс — «щелчок фокуса», единый success-момент проекта.
 *
 * Платформа: Vibration API живёт на Android; iOS его не поддерживает и молчит
 * без всяких диалогов разрешений — это не деградация, а норма (CLAUDE.md:
 * гиро и вибрация — только Android, без permission-диалогов).
 *
 * ⚠️ `prefers-reduced-motion` — выбор ПОЛЬЗОВАТЕЛЯ: при нём вибрации нет.
 * Решение принимает вызывающий (у него уже есть reduce после маунта) и
 * передаёт его сюда явным `reduce`, чтобы модуль не заводил свой matchMedia
 * в обход единого шлюза ввода (закон движка №5).
 */

export type Haptic = "snap" | "choice" | "success";

const MS: Record<Haptic, number> = {
  snap: 10,
  choice: 20,
  success: 30,
};

/** Общий на всё приложение троттлинг: два эффекта рядом не дребезжат. */
const THROTTLE_MS = 40;
let last = 0;

/**
 * Дать тактильный отклик. Молча ничего не делает, если платформа не умеет,
 * пользователь просил меньше движения или с прошлой вибрации прошло <40 мс.
 */
export function haptic(kind: Haptic, reduce: boolean | null = false): void {
  // `null` — предпочтение ещё не известно (хуки reduce отдают его до маунта).
  // Трактуем как «не запрещал»: вибрация возможна только по жесту, а жест
  // раньше маунта не случается.
  if (reduce) return;
  if (typeof navigator === "undefined" || typeof navigator.vibrate !== "function")
    return;
  const now = Date.now();
  if (now - last < THROTTLE_MS) return;
  last = now;
  try {
    navigator.vibrate(MS[kind]);
  } catch {
    /* молча: платформа не поддержала */
  }
}
